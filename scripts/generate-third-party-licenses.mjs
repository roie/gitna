import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const web = join(root, 'web')
const output = join(root, 'THIRD_PARTY_LICENSES.txt')

function readText(path) {
  return readFileSync(path, 'utf8').replace(/\r\n?/g, '\n').trim()
}

function licenseFile(directory) {
  const names = readdirSync(directory).filter((name) => /^(licen[cs]e|copying)(\..*)?$/i.test(name))
  if (names.length === 0) return null
  names.sort()
  return join(directory, names[0])
}

function packageFamily(name) {
  return name.startsWith('@') ? name.split('/')[0] : name
}

function runPnpm(args, options) {
  if (process.platform === 'win32') {
    return execFileSync(
      process.env.ComSpec ?? 'cmd.exe',
      ['/d', '/s', '/c', 'pnpm.cmd', ...args],
      options,
    )
  }
  return execFileSync('pnpm', args, options)
}

function parseJSON(value, source) {
  try {
    return JSON.parse(value)
  } catch (error) {
    throw new Error(`Invalid JSON in ${source}`, { cause: error })
  }
}

function classifyLicense(text) {
  if (text.includes('Apache License') && text.includes('Version 2.0')) return 'Apache-2.0'
  if (text.includes('Permission is hereby granted, free of charge')) return 'MIT'
  if (text.includes('Redistribution and use in source and binary forms')) return 'BSD-3-Clause'
  if (text.includes('SIL OPEN FONT LICENSE')) return 'OFL-1.1'
  throw new Error('Unrecognized license text')
}

function packageLicenseText(directory) {
  const path = licenseFile(directory)
  if (path != null) return readText(path)
  const readmePath = join(directory, 'README.md')
  try {
    const readme = readText(readmePath)
    const heading = readme.search(/^#{1,3}\s+.*licen[cs]e.*$/im)
    return heading < 0 ? null : readme.slice(heading).trim()
  } catch {
    return null
  }
}

const records = new Map()
const pnpmLicenses = parseJSON(
  runPnpm(['licenses', 'list', '--prod', '--json'], {
    cwd: web,
    encoding: 'utf8',
  }),
  'pnpm license inventory',
)

for (const [license, packages] of Object.entries(pnpmLicenses)) {
  for (const entry of packages) {
    for (const directory of entry.paths) {
      const metadata = parseJSON(
        readFileSync(join(directory, 'package.json'), 'utf8'),
        join(directory, 'package.json'),
      )
      const key = `npm:${metadata.name}@${metadata.version}`
      records.set(key, {
        name: `${metadata.name}@${metadata.version}`,
        packageName: metadata.name,
        source: metadata.homepage ?? metadata.repository?.url ?? 'npm package',
        license,
        text: packageLicenseText(directory),
      })
    }
  }
}

const familyLicenses = new Map()
for (const record of records.values()) {
  if (record.text != null)
    familyLicenses.set(`${packageFamily(record.packageName)}:${record.license}`, record.text)
}
for (const record of records.values()) {
  if (record.text != null) continue
  record.text = familyLicenses.get(`${packageFamily(record.packageName)}:${record.license}`) ?? null
  if (record.text == null) throw new Error(`No license text found for ${record.name}`)
}

execFileSync('go', ['mod', 'download', 'all'], { cwd: root, stdio: 'inherit' })

const modules = execFileSync(
  'go',
  ['list', '-m', '-f', '{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}', 'all'],
  { cwd: root, encoding: 'utf8' },
)
for (const line of modules.trim().split('\n')) {
  if (line === '') continue
  const [name, version, directory] = line.split('\t')
  const text = readText(licenseFile(directory))
  records.set(`go:${name}@${version}`, {
    name: `${name}@${version}`,
    source: `https://${name}`,
    license: classifyLicense(text),
    text,
  })
}

records.set('font:geist@1.5.1', {
  name: 'Geist font@1.5.1',
  source: 'https://github.com/vercel/geist-font',
  license: 'SIL Open Font License 1.1',
  text: readText(join(root, 'LICENSES', 'OFL-1.1.txt')),
})

const sections = [...records.entries()]
  .sort(([left], [right]) => left.localeCompare(right))
  .map(
    ([, record]) =>
      `${'='.repeat(80)}\n${record.name}\nSource: ${record.source}\nDeclared license: ${record.license}\n${'-'.repeat(80)}\n${record.text}\n`,
  )

const header = `Gitna third-party license inventory

Generated by scripts/generate-third-party-licenses.mjs from web/pnpm-lock.yaml,
installed production package metadata, go.mod, and the checked-in Geist font.
Do not edit this file manually.

`
writeFileSync(output, header + sections.join('\n'))
process.stdout.write(`Wrote ${records.size} license records to ${output}\n`)
